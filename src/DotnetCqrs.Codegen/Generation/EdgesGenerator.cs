using System.Text;
using DotnetCqrs.Codegen.Mapping;

namespace DotnetCqrs.Codegen.Generation;

/// <summary>
/// Writes a system's edges from a coordinating document as two tables (<c>Generated.SystemEdgeTables.In</c> and
/// <c>.Out</c>), data only: <c>DotnetCqrs.Edges</c> is what they mean, so the tables carry no logic of their own and
/// name no carrier. pocketcqrs writes the same tables as <c>EdgesIn</c>/<c>EdgesOut</c>.
/// </summary>
public static class EdgesGenerator
{
    public const string FileName = "Edges.g.cs";

    public static GeneratedFile Generate(SystemEdges edges)
    {
        var b = new StringBuilder();
        var alone = edges.Architecture.Length == 0;
        b.AppendLine(alone
            ? "// <auto-generated/> by dotnetcqrs-codegen from this system's own document alone. Do not edit."
            : "// <auto-generated/> by dotnetcqrs-codegen from a coordinating document. Do not edit.");
        b.AppendLine("using DotnetCqrs.Edges;");
        b.AppendLine();
        b.AppendLine("namespace Generated;");
        b.AppendLine();
        b.AppendLine(alone
            ? $"/// <summary>What system \"{edges.System}\" publishes from its own document: no edges in, and the public events whose markers list their fields.</summary>"
            : $"/// <summary>The edges of system \"{edges.System}\" in the coordinating document \"{edges.Architecture}\".</summary>");
        b.AppendLine("public static class SystemEdgeTables");
        b.AppendLine("{");
        b.AppendLine("    /// <summary>This system's document id: the name every message it sends carries (the edge message's system),");
        b.AppendLine("    /// whatever a view calls it.</summary>");
        b.AppendLine($"    public const string System = {Lit(edges.System)};");
        b.AppendLine();
        b.AppendLine("    /// <summary>The internal edges into this system: give each message a carrier delivers to Edges.Find, and send");
        b.AppendLine("    /// what EdgeIn.Translate makes of it.</summary>");
        b.AppendLine("    public static readonly IReadOnlyList<EdgeIn> In =");
        b.AppendLine("    [");
        foreach (var e in edges.In)
        {
            var fields = string.Join(", ", e.Fields.OrderBy(kv => kv.Key, StringComparer.Ordinal)
                .Select(kv => $"[{Lit(kv.Key)}] = {Lit(kv.Value)}"));
            b.AppendLine($"        new({Lit(e.Id)}, {Lit(e.FromSystem)}, {Lit(e.FromEvent)}, {e.FromVersion}, {Lit(e.Aggregate)}, {Lit(e.Command)}, {Lit(e.TargetField)},");
            b.AppendLine($"            new Dictionary<string, string> {{ {fields} }}),");
        }
        b.AppendLine("    ];");
        b.AppendLine();
        b.AppendLine("    /// <summary>The public events this system publishes, each with only the fields it publishes (its marker's");
        b.AppendLine("    /// list, or else those some edge maps): pass each committed event to Edges.Publish, and send the message it");
        b.AppendLine("    /// makes.</summary>");
        b.AppendLine("    public static readonly IReadOnlyList<EdgeOut> Out =");
        b.AppendLine("    [");
        foreach (var o in edges.Out)
            b.AppendLine($"        new({Lit(o.EventType)}, {Lit(o.System)}, {Lit(o.Event)}, {o.Version}, [{string.Join(", ", o.Fields.Select(Lit))}]),");
        b.AppendLine("    ];");
        b.AppendLine("}");
        return new GeneratedFile(FileName, b.ToString());
    }

    private static string Lit(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
